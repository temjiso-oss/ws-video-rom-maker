def font_bin():
    """4bpp パックド (1行 4バイト、上位ニブルが左)。点 = 色1"""
    out = bytearray()
    for code in range(32, 96):
        rows = FONT.get(chr(code), [''] * 7)
        rows = [r.ljust(5, '.') for r in rows] + ['.....']
        for r in rows[:8]:
            px = [1 if ch == '#' else 0 for ch in ('.' + r + '..')[:8]]
            for i in range(0, 8, 2):
                out.append(px[i] << 4 | px[i + 1])
    assert len(out) == 64 * 32
    return bytes(out)


def osdfont_bin():
    """時間表示用: 0-9 : / 空白(黒) 透明 の 14 タイル。文字 = 色15、背景 = 色14"""
    out = bytearray()
    for ch in '0123456789:/ ':
        rows = [r.ljust(5, '.') for r in FONT[ch]] + ['.....']
        for r in rows[:8]:
            px = [15 if c == '#' else 14 for c in ('.' + r + '..')[:8]]
            for i in range(0, 8, 2):
                out.append(px[i] << 4 | px[i + 1])
    out += bytes(32)                     # 透明
    assert len(out) == 14 * 32
    return bytes(out)


